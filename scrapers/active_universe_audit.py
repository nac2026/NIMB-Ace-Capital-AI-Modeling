"""Classify each of the 27 banks as ACTIVE / MERGED / DELISTED based on data signals.

A bank is ACTIVE if its latest price is within 14 days of today.
Otherwise MERGED/DELISTED (sector label often says so in scrip master)."""
import csv
from datetime import datetime, date
from pathlib import Path

OUT = Path("output")
BANKS = ["ADBL","BOKL","CCBL","CZBIL","CBL","EBL","GBIME","HBL","JBNL","KBL","LBL",
         "MBL","MEGA","NABIL","NBB","NBL","NCCB","NIB","SBI","NICA","NMB","PRVU",
         "PCBL","SANIMA","SBL","SCB","SRBL"]

master = {r["scrip"]: r for r in csv.DictReader(open(OUT/"company_info"/"scrip_master.csv"))}
today = date.today()

active, historical = [], []
for sym in BANKS:
    rows = list(csv.DictReader(open(OUT/"prices"/f"{sym}.csv")))
    latest = rows[0]["date"] if rows else "-"
    dt = datetime.strptime(latest, "%Y-%m-%d").date() if latest != "-" else None
    age = (today - dt).days if dt else 999999
    sector = master.get(sym, {}).get("sector", "?")
    name = master.get(sym, {}).get("company_name", "?")
    price_rows = len(rows)
    if age <= 14:
        active.append((sym, name, sector, latest, price_rows))
    else:
        historical.append((sym, name, sector, latest, age, price_rows))

print(f"\n=== ACTIVE commercial banks ({len(active)}) — usable for prototype ===\n")
print(f"  {'SYM':<8} {'NAME':<42} {'SECTOR':<20} {'LATEST':<12} {'ROWS':>6}")
for sym, name, sec, latest, rows in sorted(active):
    print(f"  {sym:<8} {name[:42]:<42} {sec[:20]:<20} {latest:<12} {rows:>6}")

print(f"\n=== HISTORICAL (merged/delisted) banks ({len(historical)}) — drop or tag ===\n")
print(f"  {'SYM':<8} {'NAME':<42} {'SECTOR':<20} {'LAST':<12} {'AGE_DAYS':>9}  rows")
for sym, name, sec, latest, age, rows in sorted(historical, key=lambda x: -x[4]):
    print(f"  {sym:<8} {name[:42]:<42} {sec[:20]:<20} {latest:<12} {age:>9}  {rows}")

# Write an updated config for prototype
active_symbols = sorted(s for s, *_ in active)
with open("config/banks_active.yaml", "w") as f:
    f.write("# Active commercial banks as of scrape — auto-generated by active_universe_audit.py\n")
    f.write("# Historical (merged/delisted) banks are listed separately in banks_historical.yaml\n")
    f.write("banks:\n")
    for s in active_symbols:
        name = master[s]["company_name"]
        f.write(f"  - {s:<8}  # {name}\n")

historical_symbols = sorted(s for s, *_ in historical)
with open("config/banks_historical.yaml", "w") as f:
    f.write("# Merged/delisted banks — kept for historical analysis only\n")
    f.write("banks:\n")
    for s in historical_symbols:
        name = master[s]["company_name"]
        f.write(f"  - {s:<8}  # {name}\n")

print(f"\n→ wrote config/banks_active.yaml ({len(active_symbols)} scrips)")
print(f"→ wrote config/banks_historical.yaml ({len(historical_symbols)} scrips)")
