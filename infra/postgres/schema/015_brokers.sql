-- ============================================================================
-- 015_brokers.sql — NEPSE broker code → firm-name reference dimension.
--
-- The floor sheet (and everything derived from it) identifies brokers by an
-- anonymous integer code. This table maps those codes to firm names so the
-- surveillance board / alerts / broker tools can name a counterparty instead of
-- showing "Broker #65". Slowly-changing reference data — seeded here (idempotent)
-- from the public NEPSE broker directory (hamroshare.com.np/nepse/brokers).
-- Re-running the seed refreshes names; new brokers can be appended in a later
-- migration. NOT lakehouse-synced — Postgres-owned reference dimension.
-- ============================================================================

CREATE TABLE IF NOT EXISTS brokers (
    broker       INTEGER PRIMARY KEY,
    name         TEXT NOT NULL,
    member_type  TEXT,
    source       TEXT NOT NULL DEFAULT 'hamroshare',
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

