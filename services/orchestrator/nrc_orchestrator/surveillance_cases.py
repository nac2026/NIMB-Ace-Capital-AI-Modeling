# ------------------------------------------------------------------ case build

_FLAG_TAGS = [
    ("cross_flag", "Wash-trade signature"),
    ("churn_flag", "Same-day churn"),
    ("repeat_counterparty_flag", "Repeat counterparty"),
    ("exit_liquidity_flag", "Exit liquidity"),
    ("worse_than_range_flag", "Outside day range"),
    ("bought_near_peak_flag", "Pay-up pattern"),
    ("scrip_concentration_flag", "Broker concentration"),
    ("scrip_pump_flag", "Pump pattern"),
    ("cp_flagged", "Flagged counterparty"),
]


def _pattern_headline(rows: list[dict], fundamental: dict | None = None, technical: dict | None = None) -> str:
    """One-line pattern label for the case header, from the strongest signal."""
    any_ = lambda k: any(r.get(k) for r in rows)  # noqa: E731
    max_z = max((r.get("cp_surprise_z") or 0) for r in rows)
    worst_markout = min((r.get("markout_5d_pct") if r.get("markout_5d_pct") is not None else 0) for r in rows)
    # Merit-driven headline takes the lead when both lenses are concerning together —
    # the "bad decision, not just bad execution" case the integrated verdict exists for.
    fund_bad = bool(fundamental and (fundamental.get("score") or 0) >= 0.5)
    tech_bad = bool(technical and (technical.get("score") or 0) >= 0.5)
    if fund_bad and tech_bad:
        return "Bought a fundamentally stressed name at a poor technical entry"
    if any_("cross_flag"):
        return "Cross-fund matched trade — possible wash"
    if any_("churn_flag"):
        return "Same-day buy & sell churn"
    if max_z >= 3:
        return "Statistically improbable repeat counterparty"
    if any_("exit_liquidity_flag"):
        return "Fund absorbed a counterparty's exit"
    if any_("worse_than_range_flag"):
        return "Filled outside the day's traded range"
    if max((r.get("exec_component") or 0) for r in rows) >= 0.5:
        return "Filled materially worse than prevailing market"
    if worst_markout <= -0.03:
        return "Adverse post-trade markout — price moved against us"
    if any_("bought_near_peak_flag"):
        return "Bought near the top of the 20-day range"
    tier = next((r.get("scrip_speculation_tier") for r in rows
                 if r.get("scrip_speculation_tier") in ("HIGH", "ELEVATED")), None)
    if tier:
        return f"Traded a scrip flagged speculative ({tier})"
    if fund_bad:
        return "Bought a fundamentally weak/stressed name"
    if tech_bad:
        return "Bought at a stretched technical entry"
    reasons = [x for r in rows for x in (r.get("flag_reasons") or [])]
    return reasons[0] if reasons else "Multiple weak signals"


def _signature(
    score: float,
    reasons: list[str],
    n_fills: int,
    classification: str | None = None,
    verdict: str | None = None,
) -> str:
    return hashlib.md5(
        f"{score:.1f}|{'|'.join(sorted(set(reasons)))}|{n_fills}|{classification or ''}|{verdict or ''}".encode()
    ).hexdigest()


