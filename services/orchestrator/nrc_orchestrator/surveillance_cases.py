"""Surveillance cases — group flagged internal fills into investigation cases
and write plain-language LLM explanations for them.

A "case" is the unit the CEO board reviews: all of one fund's flagged fills in
one scrip on one day (the fill cluster), with the evidence rolled up — score,
slippage, counterparty concentration, post-trade markout curve. The per-fill
rows live in internal_trade_surveillance; this module aggregates them.

Explanations are generated by the synthesizer LLM with a domain glossary in
the system prompt (interval VWAP, markout, surprise z, exit liquidity, ...)
so it can translate the quantitative flags into 2-4 sentences a portfolio CEO
can act on. Cached in surveillance_explanations keyed by a signature of the
case's score/reasons/fill-count — when the nightly rebuild changes a case,
the signature stops matching and the explanation regenerates lazily."""
