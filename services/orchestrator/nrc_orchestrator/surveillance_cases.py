def _market_context(pg: PostgresClient, scrip: str, broker: int, trade_date: str) -> dict | None:
    """Market-context intelligence for a counterparty broker in a scrip.

    From broker_flow_daily (per scrip × broker × day flows): the broker's
    historical participation over the previous 30/90 TRADING days, its share
    and rank on the trade date itself, and its 7/30-day net positioning trend
    (accumulating / distributing / balanced). This is what separates "the
    broker simply was the market that day" from "the broker barely trades
    this name yet took most of our flow"."""
    rows = pg.fetch_all(
        """
        WITH days AS (
            SELECT DISTINCT trade_date
            FROM broker_flow_daily
            WHERE scrip = %s AND trade_date <= %s::date
            ORDER BY trade_date DESC
            LIMIT 90
        ),
        ranked_days AS (
            SELECT trade_date, ROW_NUMBER() OVER (ORDER BY trade_date DESC) AS rn
            FROM days
        )
        SELECT rd.rn, f.broker, f.buy_qty, f.sell_qty, f.net_qty
        FROM broker_flow_daily f
        JOIN ranked_days rd USING (trade_date)
        WHERE f.scrip = %s
        """,
        (scrip, trade_date, scrip),
    )
    if not rows:
        return None

    def _window(lo: int, hi: int, broker_only: bool = False):
        return [r for r in rows if lo <= r["rn"] <= hi and (not broker_only or r["broker"] == broker)]

    def _shares(lo: int, hi: int) -> dict:
        win = _window(lo, hi)
        b = [r for r in win if r["broker"] == broker]
        tb = sum(float(r["buy_qty"] or 0) for r in win)
        ts = sum(float(r["sell_qty"] or 0) for r in win)
        bb = sum(float(r["buy_qty"] or 0) for r in b)
        bs = sum(float(r["sell_qty"] or 0) for r in b)
        return {
            "buy_share": round(bb / tb, 4) if tb else None,
            "sell_share": round(bs / ts, 4) if ts else None,
            "total_share": round((bb + bs) / (tb + ts), 4) if (tb + ts) else None,
            "n_days": len({r["rn"] for r in win}),
        }

    # Trade date = rn 1 (most recent trading day ≤ trade_date). Historical
    # windows EXCLUDE the trade date (rn 2..31 / 2..91) per spec.
    day = _shares(1, 1)
    day_rows = _window(1, 1)
    vol_by_broker: dict[int, float] = {}
    for r in day_rows:
        vol_by_broker[r["broker"]] = vol_by_broker.get(r["broker"], 0.0) + float(r["buy_qty"] or 0) + float(r["sell_qty"] or 0)
    ranked = sorted(vol_by_broker.items(), key=lambda kv: -kv[1])
    day_rank = next((i + 1 for i, (b, _) in enumerate(ranked) if b == broker), None)

    def _positioning(lo: int, hi: int) -> dict:
        b = _window(lo, hi, broker_only=True)
        net = sum(float(r["net_qty"] or 0) for r in b)
        gross = sum(abs(float(r["buy_qty"] or 0)) + abs(float(r["sell_qty"] or 0)) for r in b)
        direction = (net / gross) if gross else 0.0
        label = "accumulating" if direction >= 0.25 else "distributing" if direction <= -0.25 else "balanced"
        return {"net_qty": round(net), "label": label}

    return {
        "trade_date": {
            **day,
            "rank": day_rank,
            "n_brokers": len(ranked),
            "dominant": bool(day["total_share"] is not None and (day["total_share"] >= 0.25 or (day_rank or 99) <= 2)),
        },
        "hist_30d": _shares(2, 31),
        "hist_90d": _shares(2, 91),
        "positioning_7d": _positioning(1, 7),
        "positioning_30d": _positioning(1, 30),
    }


def _classify_concentration(
    fund_share: float | None,
    ctx: dict | None,
    surprise_z: float | None,
    n_trades: int,
) -> dict | None:
    """Three-tier classification of a counterparty-concentration event.

    Core idea: a counterparty taking a big share of OUR flow is unremarkable
    when it also handled a big share of the MARKET's flow (that day, or
    historically). It becomes exceptional when our exposure dwarfs both the
    broker's trade-day share and its historical participation rate."""
    if fund_share is None or ctx is None:
        return None
    day = ctx["trade_date"]
    day_share = day.get("total_share") or 0.0
    hist30 = ctx["hist_30d"].get("total_share")
    base = max(day_share, hist30 or 0.0, 0.01)
    ratio = fund_share / base

    if day["dominant"]:
        label = "Likely Normal Market Behavior" if ratio <= 2.5 else "Elevated Concentration"
    elif ratio >= 4 and (surprise_z or 0) >= 3:
        label = "Potentially Exceptional Concentration"
    elif ratio >= 2 or (surprise_z or 0) >= 3:
        label = "Elevated Concentration"
    else:
        label = "Likely Normal Market Behavior"

    # Confidence: how much evidence backs the call — history depth, number of
    # fills, and how clear-cut the ratio is (very high or comfortably low).
    hist_days = ctx["hist_30d"].get("n_days") or 0
    conf = 0.45
    conf += 0.20 if hist_days >= 20 else 0.10 if hist_days >= 5 else 0.0
    conf += 0.15 if n_trades >= 5 else 0.05 if n_trades >= 3 else 0.0
    conf += 0.15 if (ratio >= 5 or ratio <= 1.5) else 0.0
    conf = round(min(0.95, max(0.30, conf)), 2)

    fs, ds = fund_share * 100, day_share * 100
    h30 = f"{hist30 * 100:.1f}%" if hist30 is not None else "no data"
    if label == "Likely Normal Market Behavior":
        if day["dominant"]:
            rationale = (
                f"The broker handled {ds:.1f}% of all market volume in this scrip on the trade date "
                f"(rank #{day['rank']} of {day['n_brokers']}), so facing it on {fs:.1f}% of our flow is "
                f"consistent with available market liquidity."
            )
        else:
            rationale = (
                f"Our {fs:.1f}% exposure to the broker is in line with its market presence "
                f"({ds:.1f}% on the day, {h30} over the prior 30 sessions)."
            )
    elif label == "Potentially Exceptional Concentration":
        rationale = (
            f"The broker accounted for only {ds:.1f}% of the day's market volume and {h30} of the prior "
            f"30 sessions' volume, yet took {fs:.1f}% of our flow — {ratio:.1f}× its market presence. "
            f"The pairing is not explained by the broker's normal activity in this scrip."
        )
    else:
        rationale = (
            f"Our {fs:.1f}% exposure exceeds the broker's market presence ({ds:.1f}% on the day, {h30} "
            f"over 30 sessions) by {ratio:.1f}×, but not so extremely as to rule out routing or liquidity effects."
        )

    return {"label": label, "confidence": conf, "ratio": round(ratio, 1), "rationale": rationale}


def build_cases(
    pg: PostgresClient,
    *,
    min_score: float = 25.0,
    from_date: str | None = None,
    to_date: str | None = None,
) -> list[dict[str, Any]]:
    """Group flagged fills (score ≥ min_score) into investigation cases.

    from_date/to_date (YYYY-MM-DD, inclusive) narrow the case window to a
    session range; grouping and case_keys are unchanged, so cached LLM notes
    still match the filtered cases."""
    where = ["s.surveillance_score >= %s"]
    params: list[Any] = [min_score]
    if from_date:
        where.append("s.trade_date >= %s::date")
        params.append(from_date)
    if to_date:
        where.append("s.trade_date <= %s::date")
        params.append(to_date)
    rows = pg.fetch_all(
        f"""
        SELECT s.*, ob.name AS our_broker_name, cb.name AS counterparty_broker_name
        FROM internal_trade_surveillance s
        LEFT JOIN brokers ob ON ob.broker = s.our_broker
        LEFT JOIN brokers cb ON cb.broker = s.counterparty_broker
        WHERE {' AND '.join(where)}
        ORDER BY s.trade_date
        """,
        tuple(params),
    )
    if not rows:
        return []

    groups: dict[tuple, list[dict]] = defaultdict(list)
    for r in rows:
        groups[(r["client_code"], r["scrip"], str(r["trade_date"]))].append(r)

    # Cached explanations, matched by signature below.
    expl = {e["case_key"]: e for e in pg.fetch_all(
        "SELECT case_key, signature, explanation, model FROM surveillance_explanations"
    )}

    # Human findings recorded on cases — rendered as a thread under the note
    # and fed back to the LLM as analyst context when a note regenerates.
    responses: dict[str, list[dict]] = defaultdict(list)
    for r in pg.fetch_all(
        "SELECT id, case_key, author, body, created_at FROM surveillance_case_responses ORDER BY created_at"
    ):
        responses[r["case_key"]].append({
            "id": r["id"], "author": r["author"], "body": r["body"],
            "created_at": r["created_at"].isoformat() if r["created_at"] else None,
        })

    cases: list[dict[str, Any]] = []
    for (client_code, scrip, trade_date), grp in groups.items():
        micro_score = max(float(r["surveillance_score"] or 0) for r in grp)
        top = max(grp, key=lambda r: float(r["surveillance_score"] or 0))
        sides = {r["side"] for r in grp}
        qty = sum(float(r["our_qty"] or 0) for r in grp)
        notional = sum(float(r["our_value"] or 0) for r in grp)
        price = (sum(float(r["our_price"] or 0) * float(r["our_qty"] or 0) for r in grp) / qty) if qty else None
        reasons = sorted({x for r in grp for x in (r.get("flag_reasons") or [])})
        tags = sorted({label for flag, label in _FLAG_TAGS if any(r.get(flag) for r in grp)})

        # Counterparty roll-up: the broker with the most flagged volume.
        cp_qty: dict[int, float] = defaultdict(float)
        cp_names: dict[int, str | None] = {}
        for r in grp:
            if r.get("counterparty_broker") is not None:
                cp_qty[r["counterparty_broker"]] += float(r["our_qty"] or 0)
                cp_names[r["counterparty_broker"]] = r.get("counterparty_broker_name")
        top_cp = max(cp_qty, key=cp_qty.get) if cp_qty else None
        cp_label = None
        if top_cp is not None:
            cp_label = cp_names.get(top_cp) or f"Broker #{top_cp}"
            if len(cp_qty) > 1:
                cp_label += f" +{len(cp_qty) - 1} more"
        elif any(r.get("cross_flag") for r in grp):
            cp_label = "Internal · cross-fund"

        # Counterparty concentration meter (observed vs expected), from the
        # fill with the strongest surprise statistic.
        zrow = max(grp, key=lambda r: (r.get("cp_surprise_z") or float("-inf")))
        concentration = None
        if zrow.get("cp_surprise_z") is not None and zrow.get("cp_share_of_fund") is not None:
            cname = zrow.get("counterparty_broker_name") or f"Broker #{zrow.get('counterparty_broker')}"
            side_word = "sells" if zrow["side"] == "S" else "buys"
            concentration = {
                "label": f"{cname} — share of our {scrip} {side_word}",
                "value": round(float(zrow["cp_share_of_fund"]) * 100, 1),
                "expected": round(float(zrow["cp_market_share"] or 0) * 100, 1),
                "surprise_z": float(zrow["cp_surprise_z"]),
            }

        # Market-context intelligence on the concentration broker: was it a
        # dominant market participant anyway, or is our pairing exceptional?
        ctx_broker = (zrow.get("counterparty_broker") if concentration is not None else top_cp)
        market_context = _market_context(pg, scrip, ctx_broker, trade_date) if ctx_broker is not None else None
        classification = _classify_concentration(
            float(zrow["cp_share_of_fund"]) if zrow.get("cp_share_of_fund") is not None else None,
            market_context,
            float(zrow["cp_surprise_z"]) if zrow.get("cp_surprise_z") is not None else None,
            len(grp),
        )

        case_side = "CROSS" if len(sides) > 1 else ("BUY" if "B" in sides else "SELL")

        # Decision-quality lenses: was buying/selling THIS stock, at this price, on
        # this day, sound given the company's fundamentals and the chart? These fuse
        # with the upstream microstructure components into one integrated verdict —
        # the analyst's whole-picture judgement, not just "did it look manipulated".
        micro = {
            "exec": max((float(r.get("exec_component") or 0) for r in grp), default=0),
            "manip": max((float(r.get("manip_component") or 0) for r in grp), default=0),
            "counterparty": max((float(r.get("counterparty_component") or 0) for r in grp), default=0),
            "cross": max((float(r.get("cross_component") or 0) for r in grp), default=0),
            "outcome": max((float(r.get("outcome_component") or 0) for r in grp), default=0),
        }
        fundamental = technical = None
        try:
            fundamental = fundamental_factor(pg, scrip, trade_date, case_side)
            technical = technical_factor(pg, scrip, trade_date, case_side, price=price)
        except Exception as e:  # noqa: BLE001 — a missing-data lens must never sink a case
            _log.warning("decision factors failed for %s/%s/%s: %s", client_code, scrip, trade_date, e)
        verdict = integrate(micro, fundamental, technical, micro_score=micro_score)
        score = verdict["score"]  # case verdict replaces the microstructure-only score

        window = None
        case_id = f"TS-{trade_date[2:4]}{trade_date[5:7]}-{str(grp[0]['contract_number'])[-3:]}"

        case_key = f"{client_code}:{scrip}:{trade_date}"
        # Classification + the integrated verdict are part of the signature so cached
        # notes regenerate when either the market-context verdict or any factor changes.
        verdict_sig = f"{_NOTE_VERSION}:{verdict['score']:.0f}:" + ",".join(d["lens"] for d in verdict["drivers"])
        sig = _signature(score, reasons, len(grp),
                         classification["label"] if classification else None, verdict_sig)
        cached = expl.get(case_key)
        explanation = cached["explanation"] if cached and cached["signature"] == sig else None

        cases.append({
            "case_key": case_key,
            "case_id": case_id,
            "signature": sig,
            "client_code": client_code,
            "client_name": top.get("client_name"),
            "scrip": scrip,
            "trade_date": trade_date,
            "side": case_side,
            "n_fills": len(grp),
            "qty": qty,
            "notional": notional,
            "price": round(price, 2) if price else None,
            "vwap": next((float(r["interval_vwap"]) for r in grp if r.get("interval_vwap")),
                         next((float(r["day_vwap"]) for r in grp if r.get("day_vwap")), None)),
            "slippage_pct": max((r.get("slippage_vs_vwap_pct") for r in grp
                                 if r.get("slippage_vs_vwap_pct") is not None), default=None),
            "markout_5d_pct": next((r.get("markout_5d_pct") for r in grp
                                    if r.get("markout_5d_pct") is not None), None),
            "score": score,
            "tier": verdict["tier"],
            "microstructure_score": round(micro_score, 1),
            "factors": verdict["factors"],
            "drivers": verdict["drivers"],
            "fundamental": fundamental,
            "technical": technical,
            "pattern": _pattern_headline(grp, fundamental, technical),
            "counterparty": cp_label,
            "concentration": concentration,
            "market_context": market_context,
            "classification": classification,
            "flag_reasons": reasons,
            "tags": tags,
            "scrip_speculation_tier": top.get("scrip_speculation_tier"),
            "window": window,
            "explanation": explanation,
            "explanation_model": cached["model"] if cached and cached["signature"] == sig else None,
            "responses": responses.get(case_key, []),
        })

    cases.sort(key=lambda c: -c["score"])

    _attach_fills_and_markouts(pg, cases)
    return cases


def _attach_fills_and_markouts(pg: PostgresClient, cases: list[dict]) -> None:
    """Attach the fill cluster (from enriched) + D+0..D+5 markout curve."""
    for c in cases:
        fills = pg.fetch_all(
            """
            SELECT traded_at, side, our_qty, our_price
            FROM internal_trade_enriched
            WHERE client_code = %s AND scrip = %s AND trade_date = %s
            ORDER BY traded_at
            """,
            (c["client_code"], c["scrip"], c["trade_date"]),
        )
        c["fills"] = [
            {
                "t": f["traded_at"].strftime("%H:%M:%S") if f["traded_at"] else "—",
                "side": "BUY" if f["side"] == "B" else "SELL",
                "qty": float(f["our_qty"] or 0),
                "px": float(f["our_price"] or 0),
            }
            for f in fills[:8]
        ]
        c["n_fills_total"] = len(fills)
        if fills:
            t0, t1 = fills[0]["traded_at"], fills[-1]["traded_at"]
            if t0 and t1:
                c["window"] = f"{t0.strftime('%H:%M')}–{t1.strftime('%H:%M')} NPT"

        # Markout curve: drift vs our avg fill price over the next 5 trading
        # days, signed so negative = adverse for the side we took.
        c["markout_curve"] = None
        if c["price"]:
            bars = pg.fetch_all(
                """
                SELECT date, close FROM daily_bars
                WHERE scrip = %s AND date > %s
                ORDER BY date ASC LIMIT 5
                """,
                (c["scrip"], c["trade_date"]),
            )
            if bars:
                sign = 1 if c["side"] != "SELL" else -1
                curve = [0.0]
                for b in bars:
                    drift = (float(b["close"]) - c["price"]) / c["price"] * 100 * sign
                    curve.append(round(drift, 2))
                c["markout_curve"] = curve


# ------------------------------------------------------------ LLM explanations

_SYSTEM = """You are a markets-surveillance analyst at MBS Capital (Nepal), writing short
case notes for the CEO and internal staff. MBS Capital manages portfolios and executes
trades ON BEHALF OF its client funds (e.g. a mutual fund); the funds are the account the
stock was bought or sold FOR — they did not place the order themselves. So always write
in the passive, manager's voice: "this stock was bought for <Fund> on <date> at <price>",
"the position was sold for <Fund>" — NEVER "<Fund> bought" or "the fund decided". The CEO
is financially literate but not a microstructure specialist. NEPSE context: brokers are
member firms identified by code; the floor sheet records every trade with buyer/seller
broker; currency is NPR (1 lakh = Rs 100,000).

Your job is to act as the analyst and deliver ONE integrated verdict on the trade, looking
through every lens at once — execution, market manipulation, counterparty concentration,
the company's fundamentals on the trade date, and the technical entry — and say plainly
whether, taken together, it looks like a poor or suspicious decision, and why.

Glossary of the screen's terms (use plain language, not these labels):
- interval VWAP: volume-weighted average price of all market trades within
  ±15 minutes of our fill — the fair "prevailing market" benchmark.
- slippage: how much worse our fill was than that benchmark (positive = we
  overpaid on a buy / undersold on a sell). Scored relative to the scrip's own
  volatility so illiquid names aren't over-flagged.
- markout: price drift after our trade; negative = the price moved against the
  side we took (we bought and it fell / sold and it rose). Persistent negative
  markouts suggest we trade against better-informed counterparties.
- surprise z: how statistically improbable it is that the same counterparty
  broker keeps taking the other side of our flow, given that broker's actual
  market share in the scrip. z ≥ 3 ≈ very unlikely under neutral matching.
- exit liquidity: we bought while the counterparty was unwinding a position it
  had accumulated — we may be the bagholder.
- cross / churn: opposite fills across the firm's own funds within minutes
  (wash-trade signature), or the same fund buying AND selling a scrip the
  same day (volume without position change).
- speculation tier: a market-wide 0-100 score flagging scrips that look
  operator-driven (broker concentration, wash trading, pumps).
- market context: the counterparty broker's share of ALL market activity in
  the scrip — on the trade date (with its volume rank among brokers) and over
  the prior 30/90 trading sessions — plus its net positioning trend
  (accumulating / distributing / balanced). A big share of our flow is
  unremarkable when the broker also handled a big share of the market's flow;
  it is exceptional when our exposure dwarfs both its trade-day share and its
  historical participation.
- classification: the screen's own verdict on the concentration —
  "Likely Normal Market Behavior", "Elevated Concentration", or "Potentially
  Exceptional Concentration" — with a confidence score.
- fundamental health: the company's quarterly financial quality AS OF the trade
  date (sector-relative quality score 0-100, plus stress flags like high NPL, low
  capital adequacy, or a loss). Buying a fundamentally weak/stressed name is a
  concern; selling one is usually prudent — judge by the side.
- technical entry: where the fill sat on the chart on the trade date — near the top
  of the 20-day range (chasing/overbought, RSI>60) for a buy, or near the lows
  (capitulation/oversold) for a sell. A poor entry compounds the other lenses.
- integrated verdict: the screen's single 0-100 score that FUSES all the lenses
  above, escalated when several independent lenses are concerning at once (the
  "everything points the same way" signal). The factor breakdown lists each lens's
  contribution.

OUTPUT FORMAT — produce exactly these three parts, nothing else:

(1) VERDICT PARAGRAPH — 2-3 sentences in the passive manager's voice. Open with what was bought
or sold, for which fund, when, and at what price, then the overall judgement (e.g. "appears a
poor entry on several fronts" / "looks broadly defensible apart from one concern"). Synthesise
ACROSS the lenses; do not dwell on any single one.

(2) A blank line, then a BULLETED breakdown — one bullet per lens, ALWAYS in this exact order,
each line starting with "• ", each roughly the same length, each with the concrete numbers and a
short plain read:
• Broker concentration: …
• Fundamentals: …
• Technicals: …
• Execution: …
• Outcome: …
(add "• Cross/churn: …" ONLY if the case has it.)
Give every bullet COMPARABLE weight and length — broker concentration must NOT dominate. Include
the benign lenses too, stated briefly (e.g. "Technicals: neutral entry, RSI 41, mid-range" or
"Execution: in line with the market, +0.2%"). If a lens has no data, write "not available".

(3) A blank line, then a single final line beginning "Confirm: " naming the one most useful thing
the desk should check.

Rules: use the case's concrete numbers everywhere (shares, prices, %, counterparty names, NPL/
CAR/ROE, RSI / range position, markout). On the broker bullet, say whether market context SUPPORTS
the concentration (e.g. the broker was the day's #1, so it likely reflects available liquidity) or
CONTRADICTS it (the broker barely trades this name yet took most of the flow), and note the
positioning trend when it matters. Treat the contribution ranking as ranking only — it tells you
which lens scored highest, NOT how much airtime to give it; keep the bullets balanced. This is a
flag for review, NOT an accusation — never assert wrongdoing. If analyst findings are provided,
treat them as ground truth: incorporate them (e.g. "the desk confirmed this was a negotiated
block") and adjust the tone — a resolved case should read as resolved. No section headers, no
preamble — just the verdict paragraph, the bullets, and the Confirm line."""

