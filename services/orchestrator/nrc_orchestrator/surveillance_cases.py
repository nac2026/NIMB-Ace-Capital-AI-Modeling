def generate_explanations(
    pg: PostgresClient,
    *,
    case_keys: list[str] | None = None,
    min_score: float = 25.0,
    limit: int = 10,
) -> int:
    """Write LLM explanations for flagged cases that lack a current one.

    `case_keys` restricts generation to specific cases — the frontend passes
    only the cases visible on the current page, so a 300-case MODERATE flood
    never triggers 300 LLM calls. `limit` is a hard cap per invocation."""
    cases = build_cases(pg, min_score=min_score)
    todo = [c for c in cases if not c["explanation"]]
    if case_keys is not None:
        wanted = set(case_keys)
        todo = [c for c in todo if c["case_key"] in wanted]
    todo = todo[:limit]
    if not todo:
        return 0

    router = get_router()
    client = router.synthesizer()
    written = 0
    for c in todo:
        prompt = _case_prompt(c)
        try:
            result = client.complete(
                messages=[Message(role=Role.USER, content=prompt)],
                system=_SYSTEM,
                temperature=0.3,
                max_output_tokens=400,
            )
            text = (result.content or "").strip()
            if not text:
                continue
            pg.execute(
                """
                INSERT INTO surveillance_explanations (case_key, signature, explanation, model)
                VALUES (%s, %s, %s, %s)
                ON CONFLICT (case_key) DO UPDATE
                    SET signature = EXCLUDED.signature,
                        explanation = EXCLUDED.explanation,
                        model = EXCLUDED.model,
                        created_at = now()
                """,
                (c["case_key"], c["signature"], text, client.model),
            )
            written += 1
        except Exception as e:  # noqa: BLE001 — one bad case shouldn't kill the batch
            _log.warning("explanation generation failed for %s: %s", c["case_key"], e)
    return written


def _case_prompt(c: dict) -> str:
    return "\n".join(_case_facts(c) + ["", "Write the case note now."])


def case_context_block(c: dict) -> str:
    """PAGE CONTEXT block for the per-case analyst chat.

    Everything the reviewer is looking at — facts, signals, market context,
    classification, the screen's note, recorded findings — plus a compact
    glossary, so the chat agent can discuss the case without re-fetching and
    knows what the screen's terms mean. The agent still has its full tool set
    for digging deeper (broker concentration, price history, news, ...)."""
    parts = [
        f"PAGE CONTEXT: The reviewer opened internal-trade surveillance case {c['case_id']} "
        f"({c['scrip']}, {c['side']}, {c['trade_date']}) and wants to discuss it. {FIRM_NAME} manages "
        f"portfolios and executed this trade ON BEHALF OF a client fund — write in the passive "
        f"manager's voice (\"the stock was bought for the fund\"), never \"the fund bought\". The "
        f"automated screen flagged it via an integrated verdict that fuses several lenses: execution, "
        f"market manipulation, counterparty concentration, the company's fundamentals on the trade "
        f"date, and the technical entry. Unqualified questions refer to this case. Be a skeptical but "
        f"fair markets-surveillance analyst: separate what the data shows from what it cannot show, "
        f"and suggest concrete next checks. Never assert wrongdoing. You can dig deeper with your "
        f"tools — get_fundamentals / stage2_bank_screen for company health, get_technicals / "
        f"get_returns for the chart, get_broker_concentration / get_broker_accumulation for flow, "
        f"get_news / get_scrip_sentiment for context.",
        "",
        "CASE DATA:",
        *_case_facts(c),
    ]
    if c.get("explanation"):
        parts += ["", f"The screen's current case note: {c['explanation']}"]
    parts += [
        "",
        "Term glossary: integrated verdict = single 0-100 score fusing all lenses, escalated when "
        "several deviate together; slippage = fill vs ±15-min interval VWAP (positive = worse for "
        "the fund, scored in units of the scrip's own volatility); markout = post-trade price drift "
        "(negative = moved against the side taken); surprise z = how improbable the repeat "
        "counterparty pairing is given that broker's market share (z ≥ 3 ≈ very unlikely by chance); "
        "exit liquidity = the stock was bought while the counterparty unwound an accumulated "
        "position; fundamental health = sector-relative quality score + stress flags as of the trade "
        "date; technical entry = where the fill sat in the 20-day range / RSI on the trade date; "
        "classification = the screen's market-context verdict on the concentration.",
    ]
    return "\n".join(parts)


def _case_facts(c: dict) -> list[str]:
    fund = c["client_name"] or c["client_code"]
    verb = {"BUY": "bought", "SELL": "sold", "CROSS": "crossed (bought & sold)"}.get(c["side"], "traded")
    px = f" at ~Rs {c['price']:.1f}/share" if c.get("price") else ""
    lines = [
        f"Case {c['case_id']}: {c['scrip']} was {verb} for {fund} on {c['trade_date']}"
        + (f" ({c['window']})" if c.get("window") else "") + f"{px}.",
        f"Integrated verdict — severity {c['tier']}, score {c['score']:.0f}/100"
        + (f"; microstructure sub-score {c['microstructure_score']:.0f}/100."
           if c.get("microstructure_score") is not None else "."),
        f"Size: {c['qty']:.0f} shares, notional Rs {c['notional']:,.0f}, {c['n_fills_total']} fill(s).",
    ]
    # ── Factor lenses: one comparable block each, fixed order, so the note can give
    # every reason EQUAL treatment. Each block is kept to a similar footprint — the
    # broker lens is compressed (it used to dwarf the others); fundamentals/technicals
    # are expanded to match.
    def _pct(v):
        return f"{v * 100:.1f}%" if v is not None else "n/a"

    lines.append("")
    lines.append("FACTOR LENSES (each scanned as of the trade date — give them balanced, equal treatment):")

    # 1) Broker concentration (compressed: meter + market context + verdict in one block).
    if c.get("concentration") or c.get("counterparty"):
        seg = []
        m = c.get("concentration")
        if m:
            seg.append(f"{m['label']} = {m['value']}% vs ~{m['expected']}% expected from market share (surprise z {m['surprise_z']:.1f})")
        elif c.get("counterparty"):
            seg.append(f"main counterparty {c['counterparty']}")
        mc = c.get("market_context")
        if mc:
            d = mc["trade_date"]
            seg.append(f"broker was {_pct(d.get('total_share'))} of market volume that day (rank #{d.get('rank')}/{d.get('n_brokers')}), {_pct(mc['hist_30d'].get('total_share'))} over prior 30 sessions")
            seg.append(f"positioning {mc['positioning_7d']['label']} (7d) / {mc['positioning_30d']['label']} (30d)")
        if c.get("classification"):
            cl = c["classification"]
            seg.append(f"screen verdict {cl['label']} ({cl['confidence']:.0%} conf, {cl['ratio']}× presence)")
        lines.append("• BROKER CONCENTRATION: " + "; ".join(seg) + ".")
    else:
        lines.append("• BROKER CONCENTRATION: no counterparty-concentration statistic for this cluster.")

    # 2) Fundamentals (point-in-time).
    if c.get("fundamental"):
        f = c["fundamental"]
        seg = [f"{f['posture']} — quality {f.get('quality_score', 0):.0f}/100 ({f.get('tier') or 'n/a'})"]
        ratios = [x for x in (
            f"NPL {f['npl_ratio']:.1f}%" if f.get("npl_ratio") is not None else None,
            f"CAR {f['car']:.1f}%" if f.get("car") is not None else None,
            f"ROE {f['roe']:.1f}%" if f.get("roe") is not None else None,
        ) if x]
        if ratios:
            seg.append(", ".join(ratios))
        if f.get("profit_yoy_pct") is not None:
            seg.append(f"net profit YoY {f['profit_yoy_pct'] * 100:+.0f}%")
        prs = [f"{k.replace('_', ' ')} {v:.0f}th pct" for k, v in (f.get("pillars") or {}).items() if v is not None]
        if prs:
            seg.append("sector percentiles — " + ", ".join(prs))
        if f.get("pe_ratio") is not None:
            val = f"P/E {f['pe_ratio']:.1f}"
            if f.get("peer_pe") is not None:
                val += f" vs peer {f['peer_pe']:.1f}"
            if f.get("pe_vs_peer_pct") is not None:
                val += f" ({f['pe_vs_peer_pct'] * 100:+.0f}% to peer)"
            seg.append(val)
        if f.get("flags"):
            seg.append("stress flags: " + ", ".join(f["flags"]))
        lines.append(f"• FUNDAMENTALS (Q{f['quarter']} FY{f['fiscal_year_bs']}/{(f['fiscal_year_bs'] + 1) % 100:02d}): " + "; ".join(seg) + ".")
    else:
        lines.append("• FUNDAMENTALS: no point-in-time fundamentals available for this name/quarter.")

    # 3) Technicals (point-in-time entry).
    if c.get("technical"):
        t = c["technical"]
        seg = [t["posture"]]
        if t.get("pos_in_range") is not None:
            seg.append(f"fill at {t['pos_in_range'] * 100:.0f}% of the 20-day range")
        if t.get("rsi") is not None:
            seg.append(f"RSI {t['rsi']:.0f}")
        dd = [x for x in (
            f"{t['dist_sma20_pct']:+.1f}% vs 20-day avg" if t.get("dist_sma20_pct") is not None else None,
            f"{t['dist_sma50_pct']:+.1f}% vs 50-day avg" if t.get("dist_sma50_pct") is not None else None,
        ) if x]
        if dd:
            seg.append(", ".join(dd))
        if t.get("mom_1m_pct") is not None:
            seg.append(f"1-month momentum {t['mom_1m_pct']:+.1f}%")
        lines.append("• TECHNICALS: " + "; ".join(seg) + ".")
    else:
        lines.append("• TECHNICALS: no indicator data on/before the trade date.")

    # 4) Execution quality.
    if c.get("price") and c.get("vwap"):
        ex = f"filled at {c['price']:.1f} vs ±15-min market VWAP {c['vwap']:.1f}"
        if c.get("slippage_pct") is not None:
            ex += f" (slippage {c['slippage_pct'] * 100:+.2f}%)"
        lines.append("• EXECUTION: " + ex + ".")
    elif c.get("slippage_pct") is not None:
        lines.append(f"• EXECUTION: slippage vs market benchmark {c['slippage_pct'] * 100:+.2f}%.")
    else:
        lines.append("• EXECUTION: no benchmark available (fill not matched to the floor sheet).")

    # 5) Post-trade outcome.
    if c.get("markout_5d_pct") is not None:
        lines.append(f"• OUTCOME: 5-day markout {c['markout_5d_pct'] * 100:+.2f}% (negative = price moved against the side taken).")
    else:
        lines.append("• OUTCOME: post-trade markout not yet available.")

    # 6) Cross / churn (only when present).
    cc = [t for t in (c.get("tags") or []) if t in ("Wash-trade signature", "Same-day churn")]
    if cc:
        lines.append("• CROSS/CHURN: " + ", ".join(cc) + ".")

    # Contribution ranking — context only; the note must still treat lenses evenly.
    if c.get("drivers"):
        lines.append("Contribution to the score (ranking only — do NOT let it skew the balance): "
                     + "; ".join(f"{d['label']} {d['value']:.0%}" for d in c["drivers"][:6]))
    if c.get("scrip_speculation_tier"):
        lines.append(f"Market-wide speculation tier for {c['scrip']}: {c['scrip_speculation_tier']}.")
    if c.get("flag_reasons"):
        lines.append("Screen flags: " + "; ".join(c["flag_reasons"]))
    if c.get("fills"):
        lines.append("Fill cluster: " + " | ".join(f"{f['t']} {f['side']} {f['qty']:.0f}@{f['px']:.1f}" for f in c["fills"][:6]))
    if c.get("responses"):
        lines.append(
            "\nAnalyst findings recorded on this case (human ground truth — weigh these "
            "heavily; if a finding explains the pattern, say so plainly rather than "
            "re-raising the alarm):"
        )
        for r in c["responses"][-5:]:
            when = (r.get("created_at") or "")[:10]
            lines.append(f"- [{r['author']}{', ' + when if when else ''}] {r['body']}")
    return lines
