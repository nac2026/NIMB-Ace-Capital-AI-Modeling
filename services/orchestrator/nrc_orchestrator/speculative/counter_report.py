"""Assemble the COE-facing review report (markdown) from the structured findings.

Deterministic (no LLM) — the LLM reasoning already happened in verify/assess/
debate; here we just lay it out so the report is reproducible and never
hallucinates a number that wasn't in the findings."""
from __future__ import annotations

_VERDICT_EMOJI = {"GREEN": "🟢", "AMBER": "🟡", "RED": "🔴"}


def build_counter_report(report, claims: list[dict], aspects: dict[str, list[dict]], debate: dict) -> str:
    j = debate.get("judge", {})
    verdict = j.get("verdict", "AMBER")
    conf = j.get("confidence", 0.5)
    L: list[str] = []
    L.append(f"# Independent Review — {_VERDICT_EMOJI.get(verdict, '')} {verdict}")
    L.append(f"*Confidence: {conf:.0%}*\n")
    L.append("## Verdict")
    L.append(j.get("reasoning", "—") + "\n")

    if report.thesis:
        L.append("## Report thesis (as submitted)")
        rec = f" · **Recommendation:** {report.recommendation}" if report.recommendation else ""
        tp = f" · **Target:** {report.target_price}" if report.target_price else ""
        L.append(report.thesis + rec + tp + "\n")

    # Claim verification
    sup = sum(1 for c in claims if c["verdict"] == "supported")
    con = [c for c in claims if c["verdict"] == "contradicted"]
    unv = sum(1 for c in claims if c["verdict"] == "unverifiable")
    L.append("## Claim verification")
    L.append(f"Checked **{len(claims)}** claims — ✅ {sup} supported · ❌ {len(con)} contradicted · ❓ {unv} unverifiable.\n")
    if con:
        L.append("**Contradicted by our data:**")
        for c in con:
            actual = f" → actual: `{c['actual_value']}`" if c.get("actual_value") else ""
            L.append(f"- {c['claim_text']}{actual}")
        L.append("")
    L.append("| Claim | Type | Verdict | Actual |")
    L.append("|---|---|---|---|")
    for c in claims[:30]:
        mark = {"supported": "✅", "contradicted": "❌", "unverifiable": "❓"}.get(c["verdict"], "")
        L.append(f"| {c['claim_text'][:80]} | {c['claim_type']} | {mark} {c['verdict']} | {c.get('actual_value') or '—'} |")
    L.append("")

    # Aspect assessment
    if aspects:
        L.append("## Independent aspect assessment")
        for scrip, lst in aspects.items():
            if not lst:
                continue
            neg = [a for a in lst if a["rating"] == "negative"]
            tag = "  ⚠️ " + ", ".join(a["aspect"] for a in neg) if neg else ""
            L.append(f"**{scrip}**{tag}")
            for a in lst:
                icon = {"positive": "🟢", "neutral": "⚪", "negative": "🔴"}.get(a["rating"], "")
                L.append(f"- {icon} *{a['aspect']}* — {a['assessment']}")
            L.append("")

    # Debate
    L.append("## Bull vs Bear")
    L.append("**Bull case:** " + (debate.get("bull") or "—") + "\n")
    L.append("**Bear case:** " + (debate.get("bear") or "—") + "\n")
    L.append("---")
    L.append("*Generated by the NIMB Ace speculative-analysis engine. A decision-support flag, not investment advice.*")
    return "\n".join(L)
