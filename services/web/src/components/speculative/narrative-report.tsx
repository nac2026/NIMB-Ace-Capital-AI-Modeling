"use client";

import ReactMarkdown from "react-markdown";
import remarkGfm from "remark-gfm";
import { FileText, Loader2 } from "lucide-react";

export function NarrativeReport({
  narrativeMd,
  model,
  loading = false,
  status,
}: {
  narrativeMd: string | null;
  model: string | null;
  loading?: boolean;
  status?: string;
}) {
  return (
    <section className="panel p-6">
      <div className="mb-4 flex items-center justify-between gap-3 border-b pb-3" style={{ borderColor: "var(--border-subtle)" }}>
        <div className="flex items-center gap-2.5">
          <div
            className="flex h-7 w-7 items-center justify-center rounded-md"
            style={{ background: "var(--brand-soft)", color: "var(--brand)" }}
          >
            <FileText className="h-4 w-4" strokeWidth={1.75} />
          </div>
          <div>
            <h2 className="text-[15px] font-semibold tracking-tight text-fg">Executive brief</h2>
            <p className="text-[11px] text-fg-muted">
              {model ? `Generated by ${model}` : "AI-generated · anchored to the per-ticker data above"}
            </p>
          </div>
        </div>
      </div>

      {loading && (
        <div className="flex items-center gap-2 py-8 text-[13px] text-fg-muted">
          <Loader2 className="h-4 w-4 animate-spin" strokeWidth={2} />
          Generating narrative…
        </div>
      )}

      {!loading && !narrativeMd && (
        <div className="rounded-md p-4 text-[12.5px]" style={{ background: "var(--bg-subtle)", color: "var(--fg-muted)" }}>
          {status === "partial"
            ? "Narrative unavailable for this run. The data-driven flags above remain authoritative."
            : "No narrative generated yet."}
        </div>
      )}

      {!loading && narrativeMd && (
        <div className="markdown">
          <ReactMarkdown remarkPlugins={[remarkGfm]}>{narrativeMd}</ReactMarkdown>
        </div>
      )}
    </section>
  );
}
